/* Ətraflı düyməsi səhifədən çıxmır: həmin xidmətin izahı dialoqda açılır. */
(function () {
  const dialog = document.getElementById("svc-detail");
  if (!dialog) return;
  const title = dialog.querySelector("[data-svc-title]");
  const copy = dialog.querySelector("[data-svc-copy]");
  let openId = "";

  const fill = (id) => {
    const lang = document.documentElement.lang || "az";
    const dict = (window.pageI18n && (window.pageI18n[lang] || window.pageI18n.az)) || {};
    title.textContent = dict[id + ".title"] || "";
    copy.replaceChildren();
    ["d1", "d2", "d3"].forEach((part) => {
      const text = dict[id + "." + part];
      if (!text) return;
      const p = document.createElement("p");
      p.textContent = text;
      copy.appendChild(p);
    });
  };

  document.querySelectorAll(".svc-more").forEach((btn) => {
    btn.addEventListener("click", () => {
      openId = btn.dataset.svc || "";
      fill(openId);
      dialog.showModal();
      if (typeof lenis !== "undefined") lenis?.stop();
    });
  });

  dialog.querySelector(".svc-detail-close").addEventListener("click", () => dialog.close());
  dialog.addEventListener("click", (event) => {
    if (event.target === dialog) dialog.close();
  });
  dialog.addEventListener("close", () => {
    openId = "";
    if (typeof lenis !== "undefined") lenis?.start();
  });

  new MutationObserver(() => {
    if (dialog.open && openId) fill(openId);
  }).observe(document.documentElement, { attributes: true, attributeFilter: ["lang"] });
})();
