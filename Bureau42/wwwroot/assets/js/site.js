function applyLang(lang) {
  currentLang = lang;
  const dict = Object.assign({}, i18n[lang] || i18n.az, window.pageI18n?.[lang] || {});
  document.documentElement.lang = lang;
  if (dict["page.docTitle"]) document.title = dict["page.docTitle"];
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.dataset.i18nAria;
    if (dict[key]) el.setAttribute("aria-label", dict[key]);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((el) => {
    const key = el.dataset.i18nAlt;
    if (dict[key]) el.setAttribute("alt", dict[key]);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.dataset.i18nTitle;
    if (dict[key]) el.setAttribute("title", dict[key]);
  });
  document.querySelectorAll(".lang button").forEach((btn) => {
    btn.classList.toggle("is-active", btn.dataset.lang === lang);
  });
  localStorage.setItem("042-lang", lang);
  splitContent();
  splitButtons();
  syncThemeLabel();
  if (motionReady && !prefersReduced) {
    ScrollTrigger?.getAll()?.forEach((st) => {
      if (st.vars?.id === "header-sticky") return;
      st.kill();
    });
    bindMotion();
  }
}

function splitContent() {
  document.querySelectorAll(".text-invert").forEach((el) => {
    const text = el.textContent.trim();
    const words = text.split(/\s+/);
    const mid = Math.ceil(words.length / 2);
    const lines = [words.slice(0, mid).join(" "), words.slice(mid).join(" ")].filter(Boolean);
    el.innerHTML = lines.map((line) => `<div>${line}</div>`).join("");
  });
}

// Letters re-enter right to left on hover; the label moves to the button so screen readers don't spell it out.
function splitButtons() {
  if (prefersReduced) return;
  document.querySelectorAll(".theme-btn .text").forEach((textEl) => {
    const btn = textEl.closest(".theme-btn");
    const text = textEl.textContent.trim();
    if (!btn || !text) return;
    btn.setAttribute("aria-label", text);
    textEl.setAttribute("aria-hidden", "true");
    textEl.textContent = "";
    const chars = [...text];
    chars.forEach((ch, i) => {
      const span = document.createElement("span");
      span.textContent = ch === " " ? "\u00a0" : ch;
      span.style.transitionDelay = `${(chars.length - i) * 0.03}s`;
      textEl.appendChild(span);
    });
    if (btn.dataset.letters === "1") return;
    btn.dataset.letters = "1";
    btn.addEventListener("mouseenter", () => {
      const spans = btn.querySelectorAll(".text span");
      spans.forEach((span) => span.classList.remove("animate"));
      void btn.offsetWidth;
      spans.forEach((span) => span.classList.add("animate"));
    });
  });
}

function splitChars(el) {
  const text = el.textContent.trim();
  el.setAttribute("aria-label", text);
  el.textContent = "";
  text.split(/\s+/).forEach((word, i, words) => {
    const wordEl = document.createElement("span");
    wordEl.className = "split-word";
    wordEl.setAttribute("aria-hidden", "true");
    [...word].forEach((ch) => {
      const charEl = document.createElement("span");
      charEl.className = "split-char";
      charEl.textContent = ch;
      wordEl.appendChild(charEl);
    });
    el.appendChild(wordEl);
    if (i < words.length - 1) el.appendChild(document.createTextNode(" "));
  });
  return el.querySelectorAll(".split-char");
}

