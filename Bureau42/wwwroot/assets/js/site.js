function initReveal() {
  const boxes = document.querySelectorAll(".wow");
  if (!boxes.length) return;
  boxes.forEach((el) => {
    if (el.dataset.wowDelay) el.style.setProperty("--wow-delay", el.dataset.wowDelay);
  });
  if (prefersReduced || typeof IntersectionObserver === "undefined") {
    boxes.forEach((el) => el.classList.add("animated"));
    return;
  }
  const io = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (!entry.isIntersecting) return;
        entry.target.classList.add("animated");
        io.unobserve(entry.target);
      });
    },
    { threshold: 0.12, rootMargin: "0px 0px -8% 0px" }
  );
  boxes.forEach((el) => io.observe(el));
}

function scrollToHashTarget(immediate = false) {
  const hash = window.location.hash;
  if (!hash || hash.length < 2) return;
  const target = document.querySelector(hash);
  if (!target) return;
  const go = () => {
    if (lenis) lenis.scrollTo(target, { offset: -12, immediate: !!immediate || prefersReduced });
    else target.scrollIntoView({ behavior: prefersReduced || immediate ? "auto" : "smooth", block: "start" });
  };
  requestAnimationFrame(() => requestAnimationFrame(go));
}

function runPreloader() {
  const pre = document.querySelector(".preloader");
  const startMotion = () => {
    document.body.classList.remove("is-loading");
    initLenis();
    bindHeroVideo();
    bindMotion();
    initHeader();
    initReveal();
    scrollToHashTarget(true);
  };

  // The preloader plays once per tab session; later page views open straight away.
  let seen = false;
  try {
    seen = sessionStorage.getItem("042-seen") === "1";
    sessionStorage.setItem("042-seen", "1");
  } catch (_) {}

  if (!pre || prefersReduced || seen) {
    pre?.remove();
    startMotion();
    return;
  }

  const minMs = 800;
  let closing = false;

  const finish = () => {
    if (closing || !document.body.classList.contains("is-loading")) return;
    closing = true;
    pre.classList.remove("is-loading");
    pre.classList.add("is-loaded");
    window.setTimeout(() => {
      pre.style.transition = "opacity 0.45s ease";
      pre.style.opacity = "0";
      window.setTimeout(() => {
        pre.remove();
        startMotion();
      }, 450);
    }, 280);
  };

  window.setTimeout(finish, minMs);
}

const heroBlobs = new Map();

function loadHeroBlob(src) {
  if (!heroBlobs.has(src)) {
    heroBlobs.set(src, fetch(src)
      .then((res) => (res.ok ? res.blob() : null))
      .then((blob) => (blob ? URL.createObjectURL(blob) : null))
      .catch(() => null));
  }
  return heroBlobs.get(src);
}

function heroSource(video) {
  const source = [...video.querySelectorAll("source")].find((s) => !s.media || window.matchMedia(s.media).matches);
  if (!source) return null;
  const abs = (path) => (path ? new URL(path, location.href).href : "");
  return { full: abs(source.getAttribute("src")), preview: abs(source.dataset.preview) };
}

// The full file waits for the preview so the two downloads don't split the bandwidth.
function loadHeroFiles(src) {
  const preview = src.preview ? loadHeroBlob(src.preview) : Promise.resolve(null);
  return { preview, full: preview.then(() => loadHeroBlob(src.full)) };
}

function prefetchHeroVideo() {
  const video = document.querySelector(".hero-video");
  if (!video || typeof fetch !== "function") return;
  const src = heroSource(video);
  if (src) loadHeroFiles(src);
}

// In every hero-walk encode, frame 385 (at 48 fps) repeats frame 384 and the last frame repeats the one before,
// so scrubbing jumps over the first and stops before the second to keep the camera moving evenly.
const HERO_FRAME = 1 / 48;
const HERO_REPEAT_AT = 385 * HERO_FRAME;

function bindHeroVideo() {
  const hero = document.querySelector(".hero");
  const video = document.querySelector(".hero-video");
  const header = document.querySelector(".site-header");
  if (!hero || !video || video.dataset.walkBound === "1") return;
  video.dataset.walkBound = "1";

  const prepare = (el) => {
    el.muted = true;
    el.defaultMuted = true;
    el.playsInline = true;
    el.setAttribute("muted", "");
    el.setAttribute("playsinline", "");
    el.setAttribute("webkit-playsinline", "");
  };

  // A play() during scrubbing fights the seeks, so each element is unlocked only once.
  const unlock = (el) => {
    if (el.dataset.unlocked === "1") return;
    el.muted = true;
    const play = el.play();
    if (play && typeof play.then === "function") {
      play.then(() => {
        el.dataset.unlocked = "1";
        if (el.paused) return;
        el.pause();
      }).catch(() => {});
    }
  };

  const scrubber = (el) => {
    const s = { el, duration: 0, pending: null };
    const setDuration = () => {
      const next = Number(el.duration);
      if (Number.isFinite(next) && next > 0.2) s.duration = next;
    };
    const seek = (target) => {
      if (Math.abs(el.currentTime - target) < 1 / 48) return;
      if (el.seeking) {
        s.pending = target;
        return;
      }
      try {
        el.currentTime = target;
      } catch (_) {}
    };
    s.target = (progress) => {
      const t = progress * Math.max(0, s.duration - 2.5 * HERO_FRAME);
      return t >= HERO_REPEAT_AT ? t + HERO_FRAME + 0.002 : t;
    };
    s.apply = (progress) => {
      if (!s.duration) setDuration();
      if (s.duration) seek(s.target(progress));
    };
    s.shows = (progress) => s.duration > 0 && el.readyState >= 2 && !el.seeking && Math.abs(el.currentTime - s.target(progress)) < 0.05;
    s.reset = () => {
      s.duration = 0;
      s.pending = null;
    };
    el.addEventListener("loadedmetadata", () => {
      setDuration();
      unlock(el);
    });
    el.addEventListener("durationchange", setDuration);
    el.addEventListener("seeked", () => {
      if (s.pending == null) return;
      const next = s.pending;
      s.pending = null;
      seek(next);
    });
    return s;
  };

  prepare(video);
  const main = scrubber(video);
  let layer = null;
  let generation = 0;

  const dropLayer = () => {
    if (!layer) return;
    layer.el.removeAttribute("src");
    layer.el.remove();
    layer = null;
  };

  const readProgress = () => {
    const viewH = (window.visualViewport && window.visualViewport.height) || window.innerHeight;
    const total = Math.max(1, hero.offsetHeight - viewH);
    const y = lenis && typeof lenis.scroll === "number" ? lenis.scroll : window.scrollY || 0;
    const fromTop = -hero.getBoundingClientRect().top;
    const scrolled = Math.min(total, Math.max(0, Math.max(fromTop, y)));
    return scrolled / total;
  };

  // Scrubbing a network-backed video fires a range request per seek, so both files are played from local blobs.
  // The light preview sits on top until the full file has painted the same frame underneath.
  // At the very top it stays hidden: the poster is the same first frame at full resolution.
  const start = () => {
    const gen = ++generation;
    let fullSet = false;
    main.reset();
    dropLayer();
    video.removeAttribute("src");
    const src = heroSource(video);
    if (!src || typeof fetch !== "function") {
      video.preload = "auto";
      video.load();
      return;
    }
    const files = loadHeroFiles(src);
    files.preview.then((url) => {
      if (!url || gen !== generation || fullSet) return;
      const el = video.cloneNode(false);
      el.removeAttribute("id");
      delete el.dataset.unlocked;
      prepare(el);
      el.style.visibility = "hidden";
      layer = scrubber(el);
      el.src = url;
      el.preload = "auto";
      video.after(el);
    });
    files.full.then((url) => {
      if (gen !== generation) return;
      fullSet = true;
      video.src = url || src.full;
      video.preload = "auto";
    });
  };

  const tick = () => {
    if (document.body.classList.contains("nav-open")) {
      requestAnimationFrame(tick);
      return;
    }
    const progress = readProgress();
    const inHero = progress < 0.96;
    header?.classList.toggle("is-hero", inHero);
    const y = lenis && typeof lenis.scroll === "number" ? lenis.scroll : window.scrollY || 0;
    header?.classList.toggle("is-scrolled", y > 40 && !inHero);
    main.apply(progress);
    if (layer) {
      layer.apply(progress);
      if (main.shows(progress)) dropLayer();
      else layer.el.style.visibility = progress < 0.01 ? "hidden" : "";
    }
    requestAnimationFrame(tick);
  };

  const unlockAll = () => {
    unlock(video);
    if (layer) unlock(layer.el);
  };
  window.addEventListener("pointerdown", unlockAll, { once: true, passive: true });
  window.addEventListener("touchstart", unlockAll, { once: true, passive: true });

  const portrait = window.matchMedia("(orientation: portrait) and (max-aspect-ratio: 9/16)");
  if (typeof portrait.addEventListener === "function") portrait.addEventListener("change", start);
  else portrait.addListener(start);

  start();
  requestAnimationFrame(tick);
}

function initLenis() {
  if (prefersReduced || typeof Lenis === "undefined") return;
  lenis = new Lenis({
    duration: 1.15,
    smoothWheel: true,
    wheelMultiplier: 0.72,
    touchMultiplier: 1.05,
    easing: (t) => Math.min(1, 1.001 - Math.pow(2, -10 * t))
  });
  if (typeof gsap !== "undefined") {
    lenis.on("scroll", ScrollTrigger.update);
    gsap.ticker.add((time) => lenis.raf(time * 1000));
    gsap.ticker.lagSmoothing(0);
  }
}

function bindMotion() {
  motionMedia?.revert();
  motionMedia = null;
  if (prefersReduced || typeof gsap === "undefined") {
    document.querySelectorAll(".split-title").forEach((el) => {
      el.style.clipPath = "none";
      el.style.opacity = "1";
      el.style.transform = "none";
    });
    const header = document.querySelector(".site-header");
    if (document.querySelector(".hero, .hero-video")) header?.classList.add("is-hero");
    else header?.classList.remove("is-hero");
    return;
  }
  gsap.registerPlugin(ScrollTrigger);
  gsap.config({ nullTargetWarn: false });
  ScrollTrigger.config({ ignoreMobileResize: true });
  motionReady = true;

  const header = document.querySelector(".site-header");
  const hero = document.querySelector(".hero");
  if (hero) header?.classList.add("is-hero");

  motionMedia = gsap.matchMedia();

  // Vertical insets leave room for the dots and accents above Azerbaijani capitals (İ, Ə).
  document.querySelectorAll(".split-title, .section-heading").forEach((title) => {
    const chars = splitChars(title);
    if (!chars.length) return;
    gsap.fromTo(
      chars,
      { opacity: 0, x: 8, clipPath: "inset(-30% 100% -30% 0%)" },
      {
        opacity: 1,
        x: 0,
        clipPath: "inset(-30% -10% -30% 0%)",
        duration: 0.8,
        ease: "power4.out",
        stagger: Math.min(0.03, 0.9 / chars.length),
        clearProps: "all",
        scrollTrigger: {
          trigger: title,
          start: "top 90%",
          toggleActions: "play none none none"
        }
      }
    );
  });

  document.querySelectorAll(".eyebrow").forEach((eyebrow) => {
    const line = eyebrow.querySelector("i");
    const label = eyebrow.querySelector("span");
    const tl = gsap.timeline({
      scrollTrigger: {
        trigger: eyebrow,
        start: "top 92%",
        toggleActions: "play none none none"
      }
    });
    if (line) tl.fromTo(line, { scaleX: 0 }, { scaleX: 1, duration: 0.7, ease: "power3.out" });
    if (label) tl.fromTo(label, { opacity: 0, x: 8 }, { opacity: 1, x: 0, duration: 0.6, ease: "power3.out" }, line ? "-=0.45" : 0);
  });

  document.querySelectorAll(".text-invert > div").forEach((line) => {
    gsap.to(line, {
      backgroundPositionX: 0,
      ease: "none",
      scrollTrigger: {
        trigger: line,
        scrub: 1,
        start: "top 85%",
        end: "bottom center"
      }
    });
  });

  motionMedia.add("(min-width: 1200px)", () => {
    document.querySelectorAll(".scale-up-img").forEach((section) => {
      const img = section.querySelector(".scale-up");
      if (!img) return;
      gsap.to(img, {
        scale: 1.15,
        ease: "none",
        scrollTrigger: {
          trigger: section,
          start: "top bottom",
          end: "bottom center",
          scrub: 1
        }
      });
    });
  });

  if (document.querySelector(".des-portfolio-wrap")) {
    const sections = gsap.utils.toArray(".des-portfolio-panel");
    sections.forEach((section, index) => {
      const next = sections[index + 1];
      const card = section.querySelector(".project-card");
      if (!next || !card) return;
      gsap.fromTo(
        card,
        { scale: 1 },
        {
          scale: 0.94,
          ease: "none",
          scrollTrigger: {
            trigger: next,
            start: "top bottom",
            end: () => {
              const headerEl = document.querySelector(".site-header");
              const h = headerEl ? headerEl.getBoundingClientRect().height : 72;
              return `top ${Math.round(h + 8)}px`;
            },
            scrub: true
          }
        }
      );
    });
  }

  document.querySelectorAll("[data-speed]").forEach((el) => {
    const speed = Number(el.dataset.speed);
    if (!speed) return;
    gsap.to(el, {
      y: () => (1 - speed) * -120,
      ease: "none",
      scrollTrigger: {
        trigger: el.parentElement,
        start: "top bottom",
        end: "bottom top",
        scrub: true
      }
    });
  });

  ScrollTrigger.refresh();
}

