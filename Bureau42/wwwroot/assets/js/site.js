function getTheme() {
  return document.documentElement.getAttribute("data-theme") === "dark" ? "dark" : "light";
}

function getSystemTheme() {
  return window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
}

function getThemePref() {
  const pref = localStorage.getItem("042-theme-pref");
  return pref === "light" || pref === "dark" ? pref : "system";
}

function resolveTheme() {
  return getThemePref() === "system" ? getSystemTheme() : getThemePref();
}

function syncThemeLabel() {
  const dict = i18n[currentLang] || i18n.az;
  const dark = getTheme() === "dark";
  document.querySelectorAll(".theme-toggle").forEach((btn) => {
    btn.setAttribute("aria-label", dark ? dict["theme.toLight"] : dict["theme.toDark"]);
    btn.setAttribute("aria-pressed", String(dark));
  });
}

function applyTheme(theme, persist) {
  const next = theme === "dark" ? "dark" : "light";
  document.documentElement.setAttribute("data-theme", next);
  if (persist === true) localStorage.setItem("042-theme-pref", next);
  if (persist === false) localStorage.removeItem("042-theme-pref");
  syncThemeLabel();
  if (typeof ScrollTrigger !== "undefined") ScrollTrigger.refresh();
}

function initTheme() {
  applyTheme(resolveTheme());
  document.querySelectorAll(".theme-toggle").forEach((btn) => {
    btn.addEventListener("click", () => {
      const next = getTheme() === "dark" ? "light" : "dark";
      applyTheme(next, next !== getSystemTheme());
    });
  });
  const media = window.matchMedia("(prefers-color-scheme: dark)");
  const onSystemTheme = () => {
    if (getThemePref() === "system") applyTheme(getSystemTheme());
  };
  if (typeof media.addEventListener === "function") media.addEventListener("change", onSystemTheme);
  else media.addListener(onSystemTheme);
}

