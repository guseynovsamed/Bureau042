function initAccordion(selector, oneOpen) {
  document.querySelectorAll(selector).forEach((item) => {
    const btn = item.querySelector("button");
    if (!btn) return;
    btn.setAttribute("aria-expanded", String(item.classList.contains("is-open")));
    btn.addEventListener("click", (event) => {
      const open = item.classList.contains("is-open");
      if (oneOpen) {
        document.querySelectorAll(selector).forEach((el) => {
          el.classList.remove("is-open");
          el.querySelector("button")?.setAttribute("aria-expanded", "false");
        });
      }
      item.classList.toggle("is-open", !open);
      btn.setAttribute("aria-expanded", String(!open));
      if (event.detail !== 0) btn.blur();
    });
  });
}

function initForm() {
  const form = document.querySelector("#lead-form");
  if (!form) return;

  const isLocal =
    location.protocol === "file:" ||
    location.hostname === "localhost" ||
    location.hostname === "127.0.0.1";

  form.addEventListener("submit", async (event) => {
    event.preventDefault();
    if (form.classList.contains("is-sending") || form.classList.contains("is-sent")) return;

    form.classList.remove("is-error");
    form.classList.add("is-sending");

    const fd = new FormData(form);
    if (!fd.get("form-name")) fd.set("form-name", form.getAttribute("name") || "lead");

    try {
      const res = await fetch("/", {
        method: "POST",
        headers: { "Content-Type": "application/x-www-form-urlencoded" },
        body: new URLSearchParams(fd).toString()
      });
      if (!res.ok && !isLocal) throw new Error("submit-failed");
      form.classList.add("is-sent");
    } catch (err) {
      if (isLocal) form.classList.add("is-sent");
      else form.classList.add("is-error");
    } finally {
      form.classList.remove("is-sending");
    }
  });
}

let headerBound = false;

function initHeader() {
  const header = document.querySelector(".site-header");
  const top = document.querySelector(".back-top");
  const readY = () => {
    if (lenis && typeof lenis.scroll === "number") return lenis.scroll;
    return window.scrollY;
  };
  const onScroll = (y) => {
    const pos = typeof y === "number" && !Number.isNaN(y) ? y : readY();
    const banner = document.querySelector(".hero, .page-hero");
    let inHero = false;
    if (banner) {
      inHero = banner.getBoundingClientRect().bottom > 64;
    }
    header?.classList.toggle("is-hero", inHero);
    header?.classList.toggle("is-scrolled", pos > 40 && !inHero);
    top?.classList.toggle("is-on", pos > 700);
    if (top) {
      const btn = top.getBoundingClientRect();
      const onDark = [...document.querySelectorAll(".site-footer, .hero-pin, .page-hero, .proj-hero, .proj-band")].some((el) => {
        const r = el.getBoundingClientRect();
        return r.top < btn.bottom && r.bottom > btn.top;
      });
      top.classList.toggle("on-dark", onDark);
    }
  };
  if (!headerBound) {
    headerBound = true;
    if (lenis) lenis.on("scroll", ({ scroll }) => onScroll(scroll));
    window.addEventListener("scroll", () => onScroll(readY()), { passive: true });
  }
  if (typeof ScrollTrigger !== "undefined") {
    ScrollTrigger.create({
      id: "header-sticky",
      start: 0,
      end: "max",
      onUpdate: (self) => onScroll(self.scroll())
    });
  }
  onScroll(readY());
}

